#include <iostream>
using namespace std;
int main()
{

    int n = 4;
    int i = 1;

    while (i <= n)
    {
        int j = 2;
        while (j <= i)
        {
            cout << " ";
            j++;
        }
        int k = i;
        while (k <= n)

        {
            cout << "*";
            k++;
        }
        cout << endl;
        i++;
    }
    return 0;
}
